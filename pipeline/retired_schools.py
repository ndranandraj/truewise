"""Schools that have left ED's data, and where their published addresses lead.

A college page exists while ED's Field-of-Study file lists the school. The November 2026 release
dropped 156 that had pages, among them the Connecticut community colleges that merged and schools
that have closed. A published URL is a promise (see slug_registry), so each address leads to one
page that names the school and says what happened, rather than to a bare 404.

published/retired_schools.json is the record: it keeps the name, which the data no longer holds.
A school that returns to the data leaves the record and gets its page back at the same address.

refresh.sh runs this before it replaces published/, so "old" is the release being retired:

    python -m pipeline.retired_schools --release 2026-06-10
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import duckdb

from pipeline.config import PARQUET_DIR, ROOT
from pipeline.slug_registry import load as load_registry

RETIRED = ROOT / "published" / "retired_schools.json"
REDIRECTS = ROOT / "site" / "_redirects"
PAGE_PATH = "/colleges/no-longer-listed/"
BLOCK_START = "# retired_schools: generated by pipeline/retired_schools.py, do not edit by hand."
BLOCK_END = "# end retired_schools"


def load(path: Path = RETIRED) -> list[dict]:
    return json.loads(path.read_text()) if path.exists() else []


def _schools(vc: Path) -> dict[str, tuple]:
    """unitid -> (name, state) for the real institutions in a value_check parquet."""
    src = str(vc).replace("'", "''")
    rows = duckdb.connect().execute(
        f"""SELECT unitid, any_value(inst_name), any_value(state) FROM read_parquet('{src}')
            WHERE unitid <> 'NA' GROUP BY unitid"""
    )
    return {r[0]: r[1:] for r in rows.fetchall()}


def updated_record(
    old: dict[str, tuple],
    new: dict[str, tuple],
    registry: dict[str, str],
    record: list[dict],
    release: str,
) -> list[dict]:
    """The record after a refresh: earlier entries still gone, plus schools that left this time."""
    kept = [e for e in record if e["unitid"] not in new]
    known = {e["unitid"] for e in kept}
    for unitid, (name, state) in old.items():
        if unitid not in new and unitid not in known and unitid in registry:
            kept.append(
                {
                    "unitid": unitid,
                    "slug": registry[unitid],
                    "name": name,
                    "state": state,
                    "last_release": release,
                }
            )
    return sorted(kept, key=lambda e: e["slug"])


def redirect_rules(record: list[dict]) -> str:
    """Both spellings of each address: an unmatched /college/x would otherwise reach the 404."""
    lines = []
    for e in record:
        target = f"{PAGE_PATH}#{e['slug']}"
        lines.append(f"/college/{e['slug']}/ {target} 301")
        lines.append(f"/college/{e['slug']} {target} 301")
    return "\n".join([BLOCK_START, *lines, BLOCK_END]) + "\n"


def with_rules(redirects: str, record: list[dict]) -> str:
    """The _redirects file with its generated block replaced, or added at the end."""
    head, start, rest = redirects.partition(BLOCK_START)
    if start:
        tail = rest.partition(BLOCK_END)[2].lstrip("\n")
        return head + redirect_rules(record) + tail
    return redirects.rstrip("\n") + "\n\n" + redirect_rules(record)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--release", required=True, help="the release being retired, YYYY-MM-DD")
    ap.add_argument("--old", type=Path, default=ROOT / "published" / "value_check.parquet")
    ap.add_argument("--new", type=Path, default=PARQUET_DIR / "value_check.parquet")
    args = ap.parse_args()

    record = updated_record(
        _schools(args.old), _schools(args.new), load_registry(), load(), args.release
    )
    RETIRED.write_text(json.dumps(record, indent=1, ensure_ascii=False) + "\n")
    REDIRECTS.write_text(with_rules(REDIRECTS.read_text(), record))
    print(f"schools no longer in ED's data: {len(record)}")
    print(f"wrote -> {RETIRED} and {REDIRECTS}")


if __name__ == "__main__":
    main()
